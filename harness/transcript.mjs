// Renders fixtures/*/result.json as one human-readable transcript (fixtures/TRANSCRIPT.md).
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "fixtures";
let out = "# Golden fixture transcript (real git 2.52.0.windows.1)\n\nGenerated by harness/transcript.mjs from fixtures/*/result.json.\n";
for (const name of readdirSync(dir).sort()) {
  const f = join(dir, name, "result.json");
  if (!existsSync(f)) continue;
  const r = JSON.parse(readFileSync(f, "utf8"));
  out += `\n## ${name}\n\ncovers: ${r.covers.join(", ")}\n\n`;
  for (const s of r.steps) {
    if (s.write) out += `- write \`${s.write}\`\n`;
    else if (s.rm) out += `- rm \`${s.rm}\`\n`;
    else if (s.git) {
      out += `\n\`\`\`\n$ ${s.cwd !== "." ? `(cd ${s.cwd}) ` : ""}git ${s.git.map((a) => (/[\s"]/.test(a) || a === "" ? JSON.stringify(a) : a)).join(" ")}   # exit ${s.exit}\n`;
      if (s.stdout) out += s.stdout.replace(/\n?$/, "\n");
      if (s.stderr) out += s.stderr.replace(/^/gm, "[stderr] ").replace(/\[stderr\] $/, "").replace(/\n?$/, "\n");
      out += "```\n";
    }
  }
}
writeFileSync(join(dir, "TRANSCRIPT.md"), out);
console.log(`wrote ${join(dir, "TRANSCRIPT.md")} (${out.length} chars)`);
