// Generates src/usage-text.ts from golden fixtures: the -h usage blocks, the
// top-level help printed by bare `git`, and the diff --no-index usage. These
// are observed output strings (black-box), stored as data rather than rebuilt.
import { readFileSync, writeFileSync } from "node:fs";
import { rebrand } from "../src/brand.ts";

// pkb rebrand: every observed string goes through rebrand() (git -> pkb, .git -> .pkb, ...).
const fx = (n) => JSON.parse(readFileSync(`fixtures/${n}/result.json`, "utf8"), (k, v) => (typeof v === "string" && (k === "stdout" || k === "stderr") ? rebrand(v) : v));
const usage = {};
for (const s of fx("usage-texts").steps) {
  if (s.git && s.git[1] === "-h") usage[s.git[0]] = s.stdout || s.stderr;
}
// Usage printed on an argument error can differ from the -h text (cat-file shows
// "--[no-]mailmap ..." only on the error path), so error variants are kept separately.
const usageErr = {};
for (const [n, cmd] of [["cat-file", "cat-file"], ["init-bad-option", "init"], ["write-tree-nested", "write-tree"]]) {
  const st = fx(n).steps.filter((s) => s.git && s.git[0] === cmd && s.exit === 129).at(-1);
  if (st) usageErr[cmd] = st.stderr.replace(/^error: .*\n/, "");
}
for (const s of fx("usage-texts").steps) {
  if (s.git && s.exit === 129 && s.git[1] !== "-h" && s.git[0] !== "diff") usageErr[s.git[0]] = s.stderr.replace(/^error: .*\n/, "");
}
const noIndex = fx("cli-not-a-repo").steps.at(-1).stderr.replace(/^error: .*\n/, "");

let out = "// GENERATED by recon/gen-usage-text.mjs from fixtures/usage-texts, fixtures/cli-no-args\n";
out += "// and fixtures/cli-not-a-repo (observed output of git 2.52.0.windows.1). Do not edit.\n\n";
out += `export const USAGE: Record<string, string> = ${JSON.stringify(usage, null, 2)};\n\n`;
out += `export const USAGE_ERR: Record<string, string> = ${JSON.stringify(usageErr, null, 2)};\n\n`;
out += `export const DIFF_NO_INDEX_USAGE = ${JSON.stringify(noIndex)};\n`;
writeFileSync("src/usage-text.ts", out);
console.log(`usage for ${Object.keys(usage).length} commands -> src/usage-text.ts`);
